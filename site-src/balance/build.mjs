// node site-src/balance/build.mjs : writes site/balance.js, one self-contained script (no imports, no network).
// Static art is drawn here with the vendored kit; the moving parts (beam, needle, pans, weights, knob pointers)
// are rebuilt in the page by an inlined subset of the same kit, model.mjs and geometry.mjs.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { backSvg, columnSvg, panParts } from "./static.mjs";

const HERE = dirname(fileURLToPath(import.meta.url));
const KIT = join(HERE, "..", "anatomy-kit", "iso-kit.mjs");
const OUT = join(HERE, "..", "..", "site", "balance.js");
const read = (file) => readFileSync(join(HERE, file), "utf8");

// Split the kit into its top-level declarations and keep only what the page needs, with what those need.
function kitSubset(seeds) {
  const source = readFileSync(KIT, "utf8");
  const chunks = new Map();
  let name = null, body = [];
  const flush = () => { if (name) chunks.set(name, body.join("\n")); };
  for (const line of source.split("\n")) {
    const head = line.match(/^(?:export )?(?:const|function) (\w+)/);
    if (head) { flush(); name = head[1]; body = [line.replace(/^export /, "")]; }
    else if (name) body.push(line);
  }
  flush();
  const keep = new Set();
  const visit = (id) => {
    if (keep.has(id) || !chunks.has(id)) return;
    keep.add(id);
    const text = chunks.get(id);
    for (const other of chunks.keys()) if (other !== id && new RegExp(`\\b${other}\\b`).test(text)) visit(other);
  };
  seeds.forEach(visit);
  return [...chunks].filter(([id]) => keep.has(id)).map(([, text]) => text.trim()).join("\n");
}

const strip = (text) => text.replace(/^import [^;]+;\n/gm, "").replace(/^export /gm, "");
const geometry = read("geometry.mjs");
const seeds = geometry.match(/^import \{([^}]+)\}/m)[1].split(",").map((s) => s.trim());

// Shorter path data: relative coordinates after the first point of each subpath, no leading zeros.
const short = (value) => {
  const text = (Math.round(value * 10) / 10).toFixed(1).replace(/\.0$/, "").replace(/^(-?)0\./, "$1.");
  return text === "-0" ? "0" : text;
};
function compact(d) {
  const out = [];
  let x = 0, y = 0, sx = 0, sy = 0, prev = "";
  for (const [, cmd, args] of d.matchAll(/([MLZ])([^MLZ]*)/g)) {
    if (cmd === "Z") { out.push("z"); x = sx; y = sy; prev = "z"; continue; }
    const nums = args.trim().split(/[\s,]+/).map(Number);
    for (let i = 0; i < nums.length; i += 2) {
      const [ax, ay] = [nums[i], nums[i + 1]];
      if (cmd === "M" && i === 0) { out.push("M" + short(ax) + " " + short(ay)); sx = ax; sy = ay; prev = "M"; }
      else {
        const pair = short(ax - x) + (ay - y < 0 ? "" : " ") + short(ay - y);
        out.push((prev === "l" ? (ax - x < 0 ? "" : " ") : "l") + pair);
        prev = "l";
      }
      x = ax; y = ay;
    }
  }
  return out.join("");
}
const squeeze = (svg) => svg.replace(/ d="([^"]*)"/g, (_, d) => ` d="${compact(d)}"`);
const STATIC = {
  back: squeeze(backSvg()),
  column: squeeze(columnSvg()),
  pans: Object.fromEntries([["l", -1], ["r", 1]].map(([key, side]) => [key, Object.fromEntries(Object.entries(panParts(side)).map(([part, svg]) => [part, squeeze(svg)]))])),
};
const css = read("style.css").replace(/\n\s*/g, "").replace(/\s*([{};:,>])\s*/g, "$1");

// Light minification: drop whole-line comments and indentation (no multi-line strings in these sources).
const tidy = (code) => code.split("\n").map((line) => line.trim()).filter((line) => line && !line.startsWith("//")).join("\n");

const script = [
  "/* site/balance.js, generated by site-src/balance/build.mjs. Do not edit by hand.",
  "   The rotation balance (Fig 1). Drawing kit: Anatomy iso-kit, MIT licence, see site-src/anatomy-kit/LICENSE. */",
  "(function () {",
  '"use strict";',
  tidy(kitSubset(seeds)),
  tidy(strip(read("model.mjs"))),
  tidy(strip(geometry)),
  `const STATIC = ${JSON.stringify(STATIC)};`,
  `const CSS = ${JSON.stringify(css)};`,
  tidy(read("runtime.js")),
  "})();",
  "",
].join("\n");

writeFileSync(OUT, script);
console.log(`wrote site/balance.js, ${(Buffer.byteLength(script) / 1024).toFixed(1)} KB (static art ${(Buffer.byteLength(JSON.stringify(STATIC)) / 1024).toFixed(1)} KB)`);
