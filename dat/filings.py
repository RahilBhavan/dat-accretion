def page(url, raw, acts, stated, ctx=None):
    firm = (acts or stated)[0]['firm']
    filed = (acts or stated)[0]['filed']
    weeks = sorted({r['week_end'] for r in acts + stated})
    kind = doc_type(raw, url)
    base = url.rsplit('/', 1)[0] + '/'
    marks = Notes(notes_for(acts, stated, ctx))
    parts, headline = render_body(parse(raw), base, marks, kind.startswith('Exhibit'))
    if kind.startswith('Form'):
        parts = split_cover(parts)
    body = '\n'.join(parts)
    src, got = words(body_of(raw)), words(body, skip_gen=True)
    if src != got:
        i = next((k for k in range(min(len(src), len(got))) if src[k] != got[k]), min(len(src), len(got)))
        raise RuntimeError(f'{url}: restyled text differs from the filing at character {i}: '
                           f'filing {src[i - 40:i + 40]!r} / page {got[i - 40:i + 40]!r}')
    title = f'{FIRM[firm]} {kind}, filed {long_date(filed)}'
    week = ('week ending ' + weeks[0]) if len(weeks) == 1 else ('weeks ending ' + ', '.join(weeks)) if firm != 'SBET' else \
        ('filed holdings date' + ('s ' if len(weeks) > 1 else ' ') + ', '.join(weeks))
    desc = headline or f'{FIRM[firm]} {kind} filed {filed}, restyled from the SEC filing.'
    return (HEAD.format(title=esc(title), desc=esc(desc), sec=esc(url))
            + '<main id="main" class="filing">\n<header class="doc-head" ' + GEN + '>'
            + '<p class="eyebrow">Restyled SEC filing · ' + esc(FIRM[firm]) + ' · ' + esc(kind) + '</p>'
            + '<h1>' + esc(title) + '</h1>'
            + '<p class="meta">Feeds the ' + esc(week) + '. Accession <span class="num-m">' + esc(dashed(accession(url)))
            + '</span>. The text, tables and figures below are the filing\'s own, in its order and unedited; only the layout is ours. '
            + 'Images are linked, not reproduced. The filing of record is <a href="' + esc(url) + '" rel="noopener">on sec.gov</a>.</p>'
            + '</header>\n' + feeds(acts, stated, url) + (ruler(firm, weeks[-1], ctx['weekly']) if ctx else '')
            + '\n<article id="doc" class="doc" aria-label="Filing text">\n' + body + '\n</article>\n</main>\n'
            + '<footer ' + GEN + '><p>Restyled by <a href="../index.html">DAT Accretion</a> from '
            + '<a href="' + esc(url) + '" rel="noopener">' + esc(url) + '</a>. Facts as filed; no verdicts.</p></footer>\n'
            + '</body>\n</html>\n')


def index_page(entries):
    rows = []
    for firm in ('MSTR', 'BMNR', 'SBET'):
        es = sorted((e for e in entries if e['firm'] == firm), key=lambda e: (e['filed'], e['name']), reverse=True)
        if not es:
            continue
        rows.append('<section aria-labelledby="h-' + firm + '"><h2 id="h-' + firm + '">' + FIRM[firm] + '</h2><ol class="filing-list">')
        for e in es:
            rows.append('<li><a href="' + esc(e['name']) + '"><span class="num-m d">' + esc(e['filed']) + '</span>'
                        + '<span class="k">' + esc(e['kind']) + '</span><span class="t">' + esc(e['headline'] or 'Week ending ' + e['week']) + '</span></a></li>')
        rows.append('</ol></section>')
    return (HEAD.format(title='SEC filings, restyled', desc='Every SEC filing behind the page, restyled and unedited.',
                        sec='https://www.sec.gov/edgar/search/')
            .replace('<a href="index.html">All filings</a>', '<a href="../index.html">The page</a>')
            .replace('>On sec.gov<', '>EDGAR search<')
            + '<main id="main" class="filing">\n<header class="doc-head"><p class="eyebrow">Sources</p>'
            + '<h1>The SEC filings behind every figure</h1><p class="meta">' + str(len(entries))
            + ' filings, newest first. Each is restyled from the document on sec.gov with its text, tables and figures unedited, '
              'and lists the data rows it feeds.</p></header>\n<div id="doc">' + ''.join(rows) + '</div>\n</main>\n</body>\n</html>\n')


def read(path):
    with open(path, newline='') as f:
        return list(csv.DictReader(f))


def main(data_dir='data', out=OUT):
    acts, stated = read(os.path.join(data_dir, 'actions.csv')), read(os.path.join(data_dir, 'stated.csv'))
    ctx = {f: read(os.path.join(data_dir, f + '.csv')) for f in ('attribution', 'weekly', 'balances')}
    urls = sorted({r['filing_url'] for r in acts + stated if r['filing_url']})
    os.makedirs(out, exist_ok=True)
    entries = []
    for url in urls:
        a = [r for r in acts if r['filing_url'] == url]
        s = [r for r in stated if r['filing_url'] == url]
        raw = edgar.fetch(url)
        markup = page(url, raw, a, s, ctx)
        name = page_name(url)
        with open(os.path.join(out, name), 'w', newline='\n') as f:
            f.write(markup)
        m = re.search(r'<h2 class="headline">(.*?)</h2>', markup, re.S)
        r0 = (a or s)[0]
        entries.append({'name': name, 'firm': r0['firm'], 'filed': r0['filed'], 'week': r0['week_end'],
                        'kind': doc_type(raw, url), 'headline': re.sub(r'<[^>]+>', '', html.unescape(m.group(1))) if m else ''})
    keep = {e['name'] for e in entries} | {'index.html', 'filing.css'}
    for stale in set(os.listdir(out)) - keep:
        if stale.endswith('.html'):
            os.remove(os.path.join(out, stale))
    with open(os.path.join(out, 'index.html'), 'w', newline='\n') as f:
        f.write(index_page(entries))
    print(f'{len(entries)} filings restyled into {out}/')
    return 0


if __name__ == '__main__':
    sys.exit(main(*sys.argv[1:]))
