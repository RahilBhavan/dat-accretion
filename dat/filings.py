def pct(x):
    return f'{x * 100:+.1f}%'.replace('-', '−')


def ruler(firm, week, weekly):
    """Share price change from the first measured week to `week`, split exactly into its three factors
    (s = p · n · m, so 1 + Δs = (1 + Δp)(1 + Δn)(1 + Δm)), drawn as four lines on one scale, labeled at their ends.
    SharpLink is drawn as dots on its filed dates only (M40). '' before a second week exists."""
    rows = sorted((r for r in weekly if r['firm'] == firm and r['week_end'] <= week), key=lambda r: r['week_end'])
    if len(rows) < 2:
        return ''
    coin, tk = COIN[firm], {'MSTR': 'MSTR', 'BMNR': 'BMNR', 'SBET': 'SBET'}[firm]
    val = lambda r: (float(r['s']), float(r['p']), float(r['n']), float(r['s']) / (float(r['p']) * float(r['n'])))
    base = val(rows[0])
    pts = [[v / b - 1 for v, b in zip(val(r), base)] for r in rows]
    def draw(W, H, R, names, cls):
        L, T, B = 46, 14, 30
        flat = [v for p in pts for v in p]
        lo, hi = min(0, *flat), max(0, *flat)
        pad = (hi - lo) * .06 or .01
        lo, hi = lo - pad, hi + pad
        x = lambda k: L + (W - L - R) * k / (len(rows) - 1)
        y = lambda v: T + (H - T - B) * (hi - v) / (hi - lo)
        svg = [f'<svg viewBox="0 0 {W} {H}" class="ruler-fig {cls}" role="img" aria-labelledby="ruler-cap">',
               f'<line class="zero" x1="{L}" x2="{W - R}" y1="{y(0):.1f}" y2="{y(0):.1f}"/>',
               # range frame: the data's own extent, not a full axis
               f'<line class="frame" x1="{L - 8}" x2="{L - 8}" y1="{y(max(flat)):.1f}" y2="{y(min(flat)):.1f}"/>']
        for v in sorted({min(flat), 0, max(flat)}):
            svg.append(f'<text class="tick" x="{L - 12}" y="{y(v) + 4:.1f}" text-anchor="end">{pct(v) if v else "0"}</text>')
        for k in (0, len(rows) - 1):
            svg.append(f'<text class="tick" x="{x(k):.1f}" y="{H - 8}" text-anchor="{"start" if k == 0 else "end"}">'
                       f'{rows[k]["week_end"]}</text>')
        ends = []
        for j, (name, c) in reversed(list(enumerate(names))):  # share price drawn last, on top
            if firm == 'SBET':
                svg += [f'<circle class="{c}" cx="{x(k):.1f}" cy="{y(p[j]):.1f}" r="3.2"/>' for k, p in enumerate(pts)]
            else:
                d = ' '.join(f'{"M" if k == 0 else "L"}{x(k):.1f},{y(p[j]):.1f}' for k, p in enumerate(pts))
                svg.append(f'<path class="{c}" d="{d}"/>')
            ends.append([y(pts[-1][j]), name, pts[-1][j], c])
        ends.sort()
        for k in range(1, len(ends)):  # keep end labels 15px apart
            ends[k][0] = max(ends[k][0], ends[k - 1][0] + 15)
        for k in range(len(ends) - 2, -1, -1):
            ends[k][0] = min(ends[k][0], ends[k + 1][0] - 15)
        for yy, name, v, c in ends:
            svg.append(f'<text class="lbl {c}" x="{W - R + 10}" y="{yy + 4:.1f}"><tspan class="v">{pct(v)}</tspan> {esc(name)}</text>')
        return ''.join(svg) + '</svg>'
    long = [(tk + ' share price', 'acc'), (coin + ' price', 'ink'), (coin + ' per share', 'g'), ('mNAV', 'g')]
    short = [(tk, 'acc'), (coin, 'ink'), (coin + '/share', 'g'), ('mNAV', 'g')]
    figs = draw(720, 230, 180, long, 'wide') + draw(360, 220, 118, short, 'narrow')
    f = pts[-1]
    when = 'filed date' if firm == 'SBET' else 'week ending'
    cap = (f'From the {when} {rows[0]["week_end"]} to {rows[-1]["week_end"]}, {tk} closed {pct(f[0])}: {coin} price '
           f'{pct(f[1])}, {coin} per share {pct(f[2])} and mNAV {pct(f[3])}. The three multiply to the share price '
           f'change (1 + share = (1 + price)(1 + per share)(1 + mNAV)); they do not add. Closes on each week\'s price date; '
           f'{coin} per share is net coins per share from weekly.csv, and mNAV is the share price over net coin value per share.')
    return ('<section class="ruler" ' + GEN + ' aria-labelledby="ruler-h"><h2 id="ruler-h">Share price, split into its three parts</h2>'
            + figs + '<p class="caption" id="ruler-cap">' + esc(cap) + '</p></section>')


def long_date(iso):
    import datetime as dt
    d = dt.date.fromisoformat(iso)
    return f'{d:%B} {d.day}, {d.year}'


def doc_type(raw, url):
    m = re.search(r'<TYPE>([^\s<]+)', raw[:500])
    t = m.group(1) if m else ('EX-99.1' if re.search(r'ex99', url, re.I) else '8-K')
    return 'Exhibit ' + t[3:] if t.startswith('EX-') else 'Form ' + t


