"""Restyled copies of the SEC filings behind every row (`python -m dat.filings`). stdlib only.

Each filing that actions.csv or stated.csv cites is rebuilt from its cached document (data/raw/, fetched if
missing) as site/filings/<accession>-<doc>.html, in the page's type and palette. The filing's words, tables and
figures are kept in order and unedited: only layout changes. Hidden XBRL headers are dropped, images are linked
to sec.gov rather than reproduced, and an 8-K's cover page folds into a <details>. Every page links to the filing
of record and lists the CSV rows it feeds; figures that appear in those rows are marked in the text.

Guard: the words of each page's body must equal the words of the source's visible text, character for
character once whitespace is removed, or the build raises (no silent loss).
"""
import csv, html, math, os, re, sys
from html.parser import HTMLParser
from dat import edgar

OUT = os.path.join('site', 'filings')
FIRM = {'MSTR': 'Strategy', 'BMNR': 'BitMine', 'SBET': 'SharpLink'}
SKIP = {'head', 'script', 'style', 'title', 'ix:header'}
VOID = {'br', 'img', 'hr', 'meta', 'link', 'input', 'col', 'wbr', 'area', 'base'}
BLOCK = {'p', 'div', 'li', 'h1', 'h2', 'h3', 'h4', 'h5', 'h6', 'center', 'ul', 'ol', 'blockquote', 'hr'}
NUM = re.compile(r'^\(?\$?\s*(\(?[\d,]*\d(\.\d+)?\)?|[-–—])\s*%?\)?(\s*\(\d\))*\*?$')
BULLETS = ('•', '●', '○', '◦', '▪', '·', '-', '–')
GEN = 'data-gen'  # generated by this module, not the filing's text; the word guard skips it


def accession(url):
    return url.rstrip('/').split('/')[-2]


def page_name(url):
    """site/filings file name for a filing URL: <accession>-<document stem>.html."""
    return accession(url) + '-' + os.path.splitext(url.rsplit('/', 1)[1])[0] + '.html'


def dashed(acc):
    return f'{acc[:10]}-{acc[10:12]}-{acc[12:]}'


def body_of(raw):
    """Drop EDGAR's SGML wrapper (<TYPE>, <FILENAME>...) so its labels don't read as text."""
    i = raw.lower().find('<html')
    return raw[i:] if i >= 0 else raw


class Doc(HTMLParser):
    """Filing HTML -> blocks: ('p', runs, align), ('img', src), ('table', rows). A run is (text, fmt, href) with fmt
    a subset of 'bis' (bold, italic, superscript); a row is a list of cells (runs, colspan)."""
    def __init__(self):
        super().__init__(convert_charrefs=True)
        self.blocks, self.runs, self.align = [], [], ''
        self.stack = []  # (tag, bold, italic, sup, hidden, href)
        self.table = None  # rows; nested tables flatten into the outer cell
        self.depth = 0
        self.row = self.cell = None
        self.colspan = 1

    def state(self):
        b = i = s = h = False
        href = None
        for _, fb, fi, fs, fh, fa in self.stack:
            b, i, s, h, href = b or fb, i or fi, s or fs, h or fh, fa or href
        return b, i, s, h, href

    def flush(self):
        if self.runs and ''.join(t for t, _, _ in self.runs).strip():
            self.blocks.append(('p', self.runs, self.align))
        self.runs = []

    def handle_starttag(self, tag, attrs):
        a = {k: (v or '') for k, v in attrs}
        style = a.get('style', '').lower().replace(' ', '')
        if tag == 'table':
            self.depth += 1
            if self.depth == 1:
                self.flush()
                self.table = []
        elif self.depth == 1 and tag == 'tr':
            self.end_row()
            self.row = []
        elif self.depth == 1 and tag in ('td', 'th') and self.row is not None:
            self.end_cell()  # EDGAR HTML leaves some <td> unclosed
            self.cell, self.colspan = [], int(re.sub(r'\D', '', a.get('colspan') or '') or 1)
        elif tag in BLOCK and self.depth == 0:
            self.flush()
            m = re.search(r'text-align:(\w+)', style)
            self.align = m.group(1) if m else ''
        elif tag == 'br':
            self.text('\n')
        elif tag == 'img' and not self.state()[3]:
            if self.depth:
                self.text(' ')
            else:
                self.flush()
                self.blocks.append(('img', a.get('src', '')))
        if tag in VOID:
            return
        weight = re.search(r'font-weight:(\w+)', style)
        bold = tag in ('b', 'strong') or bool(weight and (weight.group(1) == 'bold' or weight.group(1).isdigit() and int(weight.group(1)) >= 600))
        italic = tag in ('i', 'em') or 'font-style:italic' in style
        sup = tag == 'sup' or 'vertical-align:super' in style or ('position:relative' in style and 'top:-' in style)
        hidden = tag in SKIP or 'display:none' in style
        href = a.get('href') if tag == 'a' and a.get('href', '').startswith(('http://', 'https://')) else None
        self.stack.append((tag, bold, italic, sup, hidden, href))

    def handle_endtag(self, tag):
        if tag in VOID:
            return
        if tag == 'table' and self.depth:
            self.depth -= 1
            if self.depth == 0:
                self.end_row()
                if self.table:
                    self.blocks.append(('table', self.table))
                self.table = self.row = self.cell = None
        elif self.depth == 1 and tag in ('td', 'th'):
            self.end_cell()
        elif self.depth == 1 and tag == 'tr':
            self.end_row()
        elif self.depth > 1 and tag in ('td', 'th', 'tr'):
            self.text(' ')
        elif tag in BLOCK and self.depth == 0:
            self.flush()
        for k in range(len(self.stack) - 1, -1, -1):
            if self.stack[k][0] == tag:
                del self.stack[k:]
                break

    def end_cell(self):
        if self.cell is not None and self.row is not None:
            self.row.append((self.cell, self.colspan))
        self.cell = None

    def end_row(self):
        self.end_cell()
        if self.row is not None and self.table is not None:
            self.table.append(self.row)
        self.row = None

    def text(self, data):
        b, i, s, h, href = self.state()
        if h:
            return
        fmt = ('b' if b else '') + ('i' if i else '') + ('s' if s else '')
        if self.depth:
            if self.cell is not None:
                self.cell.append((data, fmt, href))
        else:
            self.runs.append((data, fmt, href))

    handle_data = text


def parse(raw):
    d = Doc()
    d.feed(body_of(raw))
    d.flush()
    return d.blocks


class Visible(HTMLParser):
    """All text a browser would show, for the word guard. With skip_gen, text inside [data-gen] is left out."""
    def __init__(self, skip_gen=False):
        super().__init__(convert_charrefs=True)
        self.out, self.stack, self.skip_gen = [], [], skip_gen

    def handle_starttag(self, tag, attrs):
        if tag in VOID:
            return
        a = dict(attrs)
        style = (a.get('style') or '').lower().replace(' ', '')
        self.stack.append(tag in SKIP or 'display:none' in style or (self.skip_gen and GEN in a) or (tag == 'summary' and self.skip_gen))

    def handle_endtag(self, tag):
        if tag not in VOID and self.stack:
            self.stack.pop()

    def handle_data(self, data):
        if not any(self.stack):
            self.out.append(data)


def words(markup, skip_gen=False):
    v = Visible(skip_gen)
    v.feed(markup)
    return re.sub(r'\s+', '', ''.join(v.out).replace('\xa0', ' '))


# ---- tables ----

def cell_text(runs):
    return ' '.join(''.join(t for t, _, _ in runs).replace('\xa0', ' ').split())


def tidy(rows):
    """Drop spacer columns and empty rows; fold lone '$' into the next cell and lone ')' or '%' into the previous.
    Returns rows of (runs, colspan) with colspans over the kept columns."""
    grid = []
    for row in rows:
        cells, col = [], 0
        for runs, span in row:
            cells.append([runs, col, span])
            col += span
        for k, c in enumerate(cells):
            t = cell_text(c[0])
            if t == '$':
                nxt = next((d for d in cells[k + 1:] if cell_text(d[0])), None)
                if nxt:
                    nxt[0] = c[0] + nxt[0]
                    c[0] = []
            elif t in (')', '%', ')%', '%)'):
                prv = next((d for d in reversed(cells[:k]) if cell_text(d[0])), None)
                if prv:
                    prv[0] = prv[0] + c[0]
                    c[0] = []
        grid.append(cells)
    keep = {c[1] for cells in grid for c in cells if c[2] == 1 and cell_text(c[0])}
    for cells in grid:
        for c in cells:
            if cell_text(c[0]) and not keep & set(range(c[1], c[1] + c[2])):
                keep.add(c[1])
    out = []
    for cells in grid:
        row = [(c[0], len(keep & set(range(c[1], c[1] + c[2])))) for c in cells]
        row = [(r, n) for r, n in row if n]
        if any(cell_text(r) for r, _ in row):
            out.append(row)
    return out


# ---- rendering ----

def esc(s):
    return html.escape(s, quote=True)


class Notes:
    """Figures to mark, each with a margin note. The first time a figure appears it gets a numbered <mark>, and its
    note waits in `pending` until the block it sits in is written; later appearances are marked without a note."""
    def __init__(self, notes=None):
        self.notes, self.used, self.pending, self.n = dict(notes or {}), set(), [], 0
        keys = sorted(self.notes, key=len, reverse=True)
        self.pat = re.compile('(' + '|'.join(r'(?<![\d,.])' + re.escape(m) + r'(?![\d,]|\.\d)' for m in keys) + ')') if keys else None

    def mark(self, figure):
        s = '<mark>' + esc(figure) + '</mark>'
        if figure in self.used or not self.notes.get(figure):
            return s
        self.used.add(figure)
        self.n += 1
        self.pending.append((self.n, self.notes[figure]))
        return '<mark id="f' + str(self.n) + '">' + esc(figure) + '</mark><sup class="snr" ' + GEN + '>' + str(self.n) + '</sup>'

    def flush(self):
        """The waiting notes as one margin <aside>, or ''."""
        if not self.pending:
            return ''
        notes = ''.join('<p><span class="snn">' + str(k) + '</span>' + n + '</p>' for k, n in self.pending)
        self.pending = []
        return '<aside class="sn" ' + GEN + '>' + notes + '</aside>'


def inline(runs, marks=None):
    """Runs -> HTML with <strong>, <em>, <sup>, links and <mark> on figures the CSVs use. Whitespace collapsed."""
    merged = []
    for t, f, h in runs:
        t = t.replace('\xa0', ' ')
        if merged and merged[-1][1:] == (f, h):
            merged[-1] = (merged[-1][0] + t, f, h)
        else:
            merged.append((t, f, h))
    out, prev_space = [], True
    pat = marks.pat if marks else None
    for t, f, h in merged:
        t = re.sub(r'\s+', ' ', t)
        if prev_space:
            t = t.lstrip(' ')
        if not t:
            continue
        prev_space = t.endswith(' ')
        parts = pat.split(t) if pat else [t]
        s = ''.join(marks.mark(p) if pat and k % 2 else esc(p) for k, p in enumerate(parts))
        lead = ' ' if s.startswith(' ') and 'b' in f else ''
        if lead:
            s = s[1:]
        if 's' in f:
            s = '<sup>' + s + '</sup>'
        if 'i' in f:
            s = '<em>' + s + '</em>'
        if 'b' in f:
            s = '<strong>' + s + '</strong>'
        if h:
            s = '<a href="' + esc(h) + '" rel="noopener nofollow">' + s + '</a>'
        out.append(lead + s)
    return ''.join(out).rstrip()


def plain(runs):
    return cell_text(runs)


def is_bold(runs):
    txt = [(t, f) for t, f, _ in runs if t.strip()]
    return bool(txt) and all('b' in f for _, f in txt)


def is_italic(runs):
    txt = [(t, f) for t, f, _ in runs if t.strip()]
    return bool(txt) and all('i' in f for _, f in txt)


def render_table(rows, marks):
    rows = tidy(rows)
    if not rows:
        return ''
    if all(len(r) == 2 and cell_text(r[0][0]) in BULLETS for r in rows):
        return '<ul>' + ''.join('<li>' + inline(r[0][0], marks) + ' ' + inline(r[1][0], marks) + '</li>' for r in rows) + '</ul>'
    first_num = next((k for k, r in enumerate(rows) if any(NUM.match(cell_text(c)) for c, _ in r)), len(rows))
    width = max(sum(n for _, n in r) for r in rows)
    layout = width <= 1 or first_num == len(rows)
    def starts(row):
        col, out = 0, []
        for _, n in row:
            out.append(col)
            col += n
        return out
    numeric = {c for k, r in enumerate(rows) if k >= first_num for (x, _), c in zip(r, starts(r)) if NUM.match(cell_text(x))}
    s = ['<div class="tbl"><table class="' + ('layout' if layout else 'data') + '">']
    prev_nil = False
    for k, row in enumerate(rows):
        head = not layout and k < first_num
        tag = 'th' if head else 'td'
        figs = [cell_text(c) for c, _ in row[1:] if NUM.match(cell_text(c))]
        dash = sum(bool(re.fullmatch(r'\$?\s*[-–—]', f)) for f in figs)
        # no activity: every figure a dash, or dashes for the period with one balance beside them (ATM "available")
        nil = not head and not layout and figs and (dash == len(figs) or dash >= 2 and len(figs) - dash <= 1)
        alone = cell_text(row[0][0]) and not any(cell_text(c) for c, _ in row[1:])
        cls = ' class="sub"' if alone and not layout and k > first_num and not NUM.match(cell_text(row[0][0])) \
            and any(NUM.match(cell_text(c)) for c, _ in rows[k - 1][1:]) else ''
        if nil or (cls and prev_nil):
            cls = ' class="' + ('sub ' if cls else '') + 'nil"'
        prev_nil = nil
        s.append('<tr' + cls + '>')
        for (c, n), col in zip(row, starts(row)):
            t = cell_text(c)
            right = (NUM.match(t) and not head) or (head and n == 1 and col in numeric and col > 0)
            attrs = (' colspan="' + str(n) + '"' if n > 1 else '') + (' class="n"' if right else '')
            s.append('<' + tag + attrs + '>' + inline(c, marks) + '</' + tag + '>')
        s.append('</tr>')
    s.append('</table></div>')
    return ''.join(s)


def render_body(blocks, base, marks, exhibit):
    """Blocks -> article HTML. Returns (html, headline) where headline is an exhibit's own title, if any."""
    out, lst, imgs, headline = [], [], [b for b in blocks if b[0] == 'img'], None
    n_img = 0

    def emit(markup):
        out.append(markup)
        if marks and marks.pending:
            out.append(marks.flush())

    def close_list():
        if lst:
            emit('<ul>' + ''.join('<li>' + x + '</li>' for x in lst) + '</ul>')
            lst.clear()
    pending_bullet = prose = False
    for blk in blocks:
        kind = blk[0]
        if kind == 'img':
            close_list()
            n_img += 1
            url = blk[1] if blk[1].startswith('http') else base + blk[1]
            emit('<p class="img" ' + GEN + '>Image ' + str(n_img) + ' of ' + str(len(imgs))
                       + ' in the filing, not reproduced here: <a href="' + esc(url) + '" rel="noopener">view it on sec.gov</a>.</p>')
            continue
        if kind == 'table':
            close_list()
            emit(render_table(blk[1], marks))
            continue
        runs, align = blk[1], blk[2]
        t = plain(runs)
        if t in BULLETS:
            pending_bullet = True
            lst.append(inline(runs, marks) + ' ')
            continue
        if pending_bullet:
            lst[-1] += inline(runs, marks)
            pending_bullet = False
            continue
        if t[:1] in '•●○◦▪':
            lst.append(inline(runs, marks))
            continue
        close_list()
        body = inline(runs, marks)
        if re.fullmatch(r'Exhibit \d+(\.\d+)?', t):
            emit('<p class="exh">' + body + '</p>')
        elif re.match(r'^Item \d+\.\d+', t) and is_bold(runs):
            emit('<h2>' + body + '</h2>')
        elif exhibit and headline is None and is_bold(runs) and len(t) > 40:
            headline = t
            emit('<h2 class="headline">' + body + '</h2>')
        elif headline is not None and not prose and align == 'center' and (is_bold(runs) or is_italic(runs)):
            emit('<p class="deck">' + body + '</p>')
        elif (is_bold(runs) or is_italic(runs)) and len(t) < 110 and not t.endswith(('.', ',', ';', ':')) and not NUM.match(t):
            emit('<h3>' + body + '</h3>')
        elif re.match(r'^(\(\d+\)|\*)\s?\S', t) and len(t) < 600:
            emit('<p class="fn">' + body + '</p>')
        else:
            prose = True
            emit('<p' + (' class="c"' if align == 'center' and len(t) < 200 else '') + '>' + body + '</p>')
    close_list()
    return out, headline


def split_cover(parts):
    """An 8-K's cover page (everything before the first Item heading) folds into <details>."""
    k = next((i for i, p in enumerate(parts) if p.startswith('<h2>') and re.match(r'<h2>(<[^>]+>)*Item', p)), None)
    if not k:
        return parts
    return ['<details class="cover"><summary>Cover page</summary>'] + parts[:k] + ['</details>'] + parts[k:]


